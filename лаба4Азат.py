# Задаем массив вручную для проверки (целые числа)
arr = [0, -5, 3, 2, -1, 0, 4, -2, 0]
n = len(arr)
print("Исходный массив:", arr)

# --- Пункт 1: Произведение элементов с четными номерами ---
# Внимание: "Четные номера" — это 2-й, 4-й, 6-й элемент (в Python их индексы 1, 3, 5...)
product_even = 1
for i in range(1, n, 2):  # range(начало, конец, шаг). Шаг 2 дает нечетные индексы
    product_even *= arr[i]
print(f"1. Произведение элементов с четными номерами: {product_even}")

# --- Пункт 2: Сумма между первым и последним нулевыми элементами ---
# Находим индексы нулей
indices_zero = [i for i, x in enumerate(arr) if x == 0]

if len(indices_zero) >= 2:
    first_zero = indices_zero[0]  # Первый ноль
    last_zero = indices_zero[-1]  # Последний ноль

    # Берем срез между ними и считаем сумму
    sum_between = sum(arr[first_zero + 1: last_zero])
    print(f"2. Сумма между первым и последним нулем: {sum_between}")
else:
    print("2. В массиве меньше двух нулей!")

# --- Пункт 3: Преобразование (сначала положительные, потом отрицательные) ---
# Нули по условию считаются положительными, поэтому используем >= 0
positive_part = [x for x in arr if x >= 0]
negative_part = [x for x in arr if x < 0]

# Склеиваем два списка
new_arr = positive_part + negative_part
print("3. Преобразованный массив:", new_arr)